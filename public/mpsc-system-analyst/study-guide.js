/* Study guide interactions: theme, search, revised-ticks, scroll-spy.
   No build step and no dependencies — this file is loaded directly by
   study-guide.html, which is itself generated by build_study_guide.py. */

(function () {
  'use strict';

  var LS_THEME = 'sg.theme';
  var LS_DONE = 'sg.tech1.done';

  /* ------------------------------------------------------------- theme */
  var root = document.documentElement;
  var saved = localStorage.getItem(LS_THEME);
  if (saved) root.setAttribute('data-theme', saved);

  document.getElementById('themeBtn').addEventListener('click', function () {
    var order = ['auto', 'light', 'dark'];
    var next = order[(order.indexOf(root.getAttribute('data-theme')) + 1) % order.length];
    root.setAttribute('data-theme', next);
    localStorage.setItem(LS_THEME, next);
  });

  document.getElementById('printBtn').addEventListener('click', function () {
    window.print();
  });

  /* ------------------------------------------------- revised checkboxes */
  var boxes = Array.prototype.slice.call(document.querySelectorAll('[data-done]'));
  var progCount = document.getElementById('progCount');
  var done = {};
  try {
    done = JSON.parse(localStorage.getItem(LS_DONE) || '{}');
  } catch (e) {
    done = {};
  }

  function paint() {
    var n = 0;
    boxes.forEach(function (box) {
      var id = box.getAttribute('data-done');
      var on = !!done[id];
      box.checked = on;
      var section = document.getElementById(id);
      if (section) section.classList.toggle('is-done', on);
      var link = document.querySelector('.gnav a[href="#' + id + '"]');
      if (link) link.classList.toggle('is-done', on);
      if (on) n++;
    });
    progCount.textContent = n;
  }

  boxes.forEach(function (box) {
    box.addEventListener('change', function () {
      var id = box.getAttribute('data-done');
      if (box.checked) done[id] = 1; else delete done[id];
      localStorage.setItem(LS_DONE, JSON.stringify(done));
      paint();
    });
  });

  document.getElementById('resetProg').addEventListener('click', function () {
    if (!confirm('Clear all "revised" ticks?')) return;
    done = {};
    localStorage.removeItem(LS_DONE);
    paint();
  });

  paint();

  /* ------------------------------------------------------------ search */
  var search = document.getElementById('search');
  var clusters = Array.prototype.slice.call(document.querySelectorAll('.cluster'));
  var cramBlocks = Array.prototype.slice.call(document.querySelectorAll('.cram-block'));

  // Cache each searchable block's text once. textContent on every keystroke
  // across ~400 questions is what makes naive versions of this feel laggy.
  var index = clusters.concat(cramBlocks).map(function (el) {
    return { el: el, text: el.textContent.toLowerCase() };
  });

  var noRes = document.createElement('div');
  noRes.className = 'nores';
  noRes.hidden = true;
  noRes.textContent = 'Nothing matches that.';
  document.querySelector('.gmain').appendChild(noRes);

  var timer = null;
  search.addEventListener('input', function () {
    clearTimeout(timer);
    timer = setTimeout(runSearch, 120);
  });

  function runSearch() {
    var q = search.value.trim().toLowerCase();
    var hits = 0;

    index.forEach(function (entry) {
      var show = !q || entry.text.indexOf(q) !== -1;
      entry.el.classList.toggle('hidden-by-search', !show);
      if (show) hits++;
    });

    // Hide a part heading and the intro when a search is active, so the page
    // does not read as a mostly-empty document with stray headings.
    document.querySelectorAll('.part-title, .part-sub, .intro, .navtop')
      .forEach(function (el) { el.classList.toggle('hidden-by-search', !!q); });

    // A question bank is collapsed by default; if the match is inside one,
    // the user would see an apparently empty topic. Open them while searching.
    document.querySelectorAll('.qbank').forEach(function (d) {
      if (q) { d.open = true; } else { d.open = false; }
    });

    noRes.hidden = !(q && hits === 0);
  }

  // Esc clears the search from anywhere on the page.
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && search.value) {
      search.value = '';
      runSearch();
      search.blur();
    } else if (e.key === '/' && document.activeElement !== search) {
      e.preventDefault();
      search.focus();
    }
  });

  /* -------------------------------------------------------- scroll-spy */
  var links = {};
  document.querySelectorAll('.gnav a[href^="#"]').forEach(function (a) {
    links[a.getAttribute('href').slice(1)] = a;
  });

  if ('IntersectionObserver' in window) {
    var visible = new Set();
    var spy = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) visible.add(entry.target.id);
        else visible.delete(entry.target.id);
      });
      Object.keys(links).forEach(function (id) {
        links[id].classList.toggle('active', visible.has(id));
      });
    }, { rootMargin: '-110px 0px -70% 0px' });

    clusters.forEach(function (c) { spy.observe(c); });
  }
})();
